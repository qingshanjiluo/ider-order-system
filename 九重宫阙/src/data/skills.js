/**
 * 按元素筛选技能
 * @param {string} element - 元素类型 ('fire' | 'water' | 'earth' | 'lightning' | 'wind' | 'dark' | 'holy' | 'none')
 * @returns {Array} 匹配的技能数组
 */
export function getSkillsByElement(element) {
  return SKILLS.filter((s) => s.element === element);
}

/**
 * 按类型筛选技能
 * @param {string} type - 技能类型 ('active' | 'passive')
 * @returns {Array} 匹配的技能数组
 */
export function getSkillsByType(type) {
  return SKILLS.filter((s) => s.type === type);
}

/**
 * 按来源筛选技能
 * @param {string} source - 技能来源 ('drop' | 'shop' | 'guild' | 'quest' | 'hidden' | 'forge' | 'achievement')
 * @returns {Array} 匹配的技能数组
 */
export function getSkillsBySource(source) {
  return SKILLS.filter((s) => s.source === source);
}

/**
 * 按ID获取单个技能
 * @param {string} id - 技能唯一标识
 * @returns {Object|null} 技能对象或null
 */
export function getSkillById(id) {
  return SKILLS.find((s) => s.id === id) || null;
}

/**
 * 按品质筛选技能
 * @param {string} quality - 技能品质
 * @returns {Array} 匹配的技能数组
 */
export function getSkillsByQuality(quality) {
  return SKILLS.filter((s) => s.quality === quality);
}

/**
 * 按稀有度筛选技能
 * @param {string} rarity - 技能稀有度
 * @returns {Array} 匹配的技能数组
 */
export function getSkillsByRarity(rarity) {
  return SKILLS.filter((s) => s.rarity === rarity);
}

/**
 * 按槽位筛选技能
 * @param {string} slot - 技能槽位 ('main' | 'sub' | 'ultimate')
 * @returns {Array} 匹配的技能数组
 */
export function getSkillsBySlot(slot) {
  return SKILLS.filter((s) => s.slot === slot);
}

/**
 * 获取所有隐藏技能
 * @returns {Array} 隐藏技能数组
 */
export function getHiddenSkills() {
  return SKILLS.filter((s) => s.is_hidden);
}

/**
 * 获取满足指定境界要求的技能
 * @param {string} realm - 当前境界
 * @param {Array} realmOrder - 境界顺序数组（从小到大）
 * @returns {Array} 可学习的技能数组
 */
export function getSkillsAvailableForRealm(realm, realmOrder) {
  const realmIndex = realmOrder.indexOf(realm);
  if (realmIndex === -1) return [];
  return SKILLS.filter((s) => {
    const reqIndex = realmOrder.indexOf(s.required_realm);
    return reqIndex !== -1 && reqIndex <= realmIndex;
  });
}

/**
 * 获取元素克制关系
 * @param {string} attacker - 攻击方元素
 * @param {string} defender - 防御方元素
 * @returns {number} 伤害倍率 (1.2=克制, 0.8=被克制, 1.0=无关系)
 */
export function getElementAdvantage(attacker, defender) {
  if (attacker === 'none' || defender === 'none') return 1.0;
  const attackerEl = ELEMENTS[attacker];
  if (!attackerEl) return 1.0;
  if (attackerEl.strong.includes(defender)) return 1.2;
  if (attackerEl.weak.includes(defender)) return 0.8;
  return 1.0;
}

/**
 * 按灵力消耗范围筛选技能
 * @param {number} minCost - 最低消耗
 * @param {number} maxCost - 最高消耗
 * @returns {Array} 匹配的技能数组
 */
export function getSkillsByManaCost(minCost, maxCost) {
  return SKILLS.filter((s) => s.mana_cost >= minCost && s.mana_cost <= maxCost);
}

/**
 * 按伤害倍率范围筛选技能
 * @param {number} minMult - 最低倍率
 * @param {number} maxMult - 最高倍率
 * @returns {Array} 匹配的技能数组
 */
export function getSkillsByDamageMult(minMult, maxMult) {
  return SKILLS.filter((s) => s.damage_mult >= minMult && s.damage_mult <= maxMult);
}

/**
 * 检查技能前置条件是否满足
 * @param {string} skillId - 技能ID
 * @param {Array} learnedSkills - 已学技能ID数组
 * @returns {boolean} 是否满足前置条件
 */
export function meetsPrerequisites(skillId, learnedSkills) {
  const skill = getSkillById(skillId);
  if (!skill) return false;
  return skill.prerequisites.every((pre) => learnedSkills.includes(pre));
}

/**
 * 获取技能升级后的属性（简化线性成长）
 * @param {Object} skill - 技能对象
 * @param {number} level - 目标等级
 * @returns {Object} 升级后的属性
 */
export function getSkillStatsAtLevel(skill, level) {
  if (level < 1 || level > skill.max_level) return null;
  const ratio = (level - 1) / (skill.max_level - 1);
  return {
    ...skill,
    current_level: level,
    mana_cost: Math.floor(skill.mana_cost * (1 + ratio * 0.3)),
    damage_mult: parseFloat((skill.damage_mult * (1 + ratio * 0.5)).toFixed(2)),
    effect_value: parseFloat((skill.effect_value * (1 + ratio * 0.4)).toFixed(3)),
    upgrade_cost: Math.floor(skill.upgrade_cost * (1 + ratio * 0.8)),
  };
}

/**
 * 统计各元素技能数量
 * @returns {Object} 元素 => 数量 映射
 */
export function countSkillsByElement() {
  const counts = {};
  for (const key of Object.keys(ELEMENTS)) {
    counts[key] = SKILLS.filter((s) => s.element === key).length;
  }
  return counts;
}

/**
 * 获取完整技能信息（含元素详情）
 * @param {string} skillId - 技能ID
 * @returns {Object|null} 技能完整信息
 */
export function getSkillWithElement(skillId) {
  const skill = getSkillById(skillId);
  if (!skill) return null;
  return {
    ...skill,
    element_info: ELEMENTS[skill.element],
  };
}
